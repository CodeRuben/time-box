type SkillPlayerData = readonly [
  name: string,
  position: Exclude<Position, "DST">,
  nflTeam: string,
  espnId: string,
];

type DefensePlayerData = readonly [name: string, position: "DST", nflTeam: string];

type PlayerData = SkillPlayerData | DefensePlayerData;

function playerKey(data: PlayerData): PlayerKey {
  if (data[1] === "DST") {
    return `team:${data[2]}`;
  }

  return `espn:${data[3]}`;
}

function playerHeadshot(data: PlayerData): string | null {
  if (data[1] === "DST") {
    return getTeamLogo(data[2]);
  }

  return getPlayerHeadshotUrl(data[3]);
}

