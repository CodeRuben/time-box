export const PLAYERS: Player[] = PLAYER_DATA.map((data, index) => {
  const [name, position, nflTeam] = data;
  const rank = index + 1;
  const player = {
    id: rank,
    key: playerKey(data),
    rank,
    name,
    position,
    nflTeam,
    bye: BYE_WEEKS[nflTeam],
    headshot: playerHeadshot(data),
  };

  return {
    ...player,
    signals: getPlayerSignals(player),
  };
});

export const PLAYER_NAME_BY_KEY: ReadonlyMap<PlayerKey, string> = new Map(
  PLAYERS.map((player) => [player.key, player.name]),
);
